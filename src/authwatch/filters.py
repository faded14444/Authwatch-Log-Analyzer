"""Drop events that are almost always noise before running detections.

Keeping all noise rules in one place makes false-positive tuning easy to find
and easy to explain.
"""

from __future__ import annotations

import ipaddress
from collections.abc import Iterable

from authwatch.models import AuthEvent

_EMPTY = {"", "-"}
_IGNORED_USERS = {"anonymous logon"}
LOGON_TYPE_RDP = 10  # RemoteInteractive


def _is_loopback(ip: str) -> bool:
    try:
        addr = ipaddress.ip_address(ip)
    except ValueError:
        return False
    if isinstance(addr, ipaddress.IPv6Address) and addr.ipv4_mapped is not None:
        addr = addr.ipv4_mapped
    return addr.is_loopback


def is_noise(event: AuthEvent) -> bool:
    """Return True for events that should not be analysed.

    - no source IP: local/service logons, nothing to attribute an attack to
    - loopback IP: the machine talking to itself - EXCEPT RDP logons. RDP from
      127.0.0.1 is never normal: it is the signature of RDP tunnelling (ngrok,
      plink, chisel), so attacks through a tunnel must stay visible.
    - machine accounts (ending in "$") and ANONYMOUS LOGON: generated by Windows itself
    """
    ip = (event.source_ip or "").strip()
    if ip in _EMPTY:
        return True
    if _is_loopback(ip) and event.logon_type != LOGON_TYPE_RDP:
        return True

    user = (event.username or "").strip()
    if user in _EMPTY or user.endswith("$"):
        return True
    return user.lower() in _IGNORED_USERS


def filter_noise(events: Iterable[AuthEvent]) -> list[AuthEvent]:
    return [e for e in events if not is_noise(e)]
